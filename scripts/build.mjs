// Bundles server/lib/*.js + server/entry.js into one QuickJS-compatible file,
// generates dist/plugin.json and packs the installable zip.
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { zipSync } from 'fflate'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIST = join(ROOT, 'dist')
const ORDER = ['hash.js', 'hosts.js', 'hints.js', 'catalog.js', 'i18n.js', 'bannertext.js', 'config.js', 'versions.js', 'transform.js', 'csp.js', 'inject.js', 'pipeline.js', 'scan.js', 'scanstore.js']

rmSync(DIST, { recursive: true, force: true })
mkdirSync(join(DIST, 'server'), { recursive: true })

// Drops import lines; lib files lose their `export` keyword, the entry keeps it
// (only `activate` is exported there).
const strip = (src, keepExports) => src
  .split('\n').filter((l) => !/^\s*import\s/.test(l)).join('\n')
  .replace(keepExports ? /$^/ : /^export\s+(?=(const|function|async function|let|class)\b)/gm, '')

let bundle = '// instatic.consent server bundle (generated by scripts/build.mjs)\n'
for (const f of ORDER) bundle += `\n// ---- ${f}\n` + strip(readFileSync(join(ROOT, 'server/lib', f), 'utf8'), false)
bundle += '\n// ---- entry.js\n' + strip(readFileSync(join(ROOT, 'server/entry.js'), 'utf8'), true)
writeFileSync(join(DIST, 'server/index.js'), bundle)

const { settingsSchema } = await import(pathToFileURL(join(ROOT, 'server/lib/config.js')).href)
const manifest = JSON.parse(readFileSync(join(ROOT, 'plugin.base.json'), 'utf8'))
manifest.settings = settingsSchema()
writeFileSync(join(DIST, 'plugin.json'), JSON.stringify(manifest, null, 2))

const files = { 'plugin.json': readFileSync(join(DIST, 'plugin.json')), 'server/index.js': readFileSync(join(DIST, 'server/index.js')), 'LICENSE': readFileSync(join(ROOT, 'LICENSE')), 'README.md': readFileSync(join(ROOT, 'README.md')), 'icon.svg': readFileSync(join(ROOT, 'icon.svg')) }
const walk = (dir) => readdirSync(dir).flatMap((n) => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p] })
for (const p of walk(join(ROOT, 'frontend'))) files[relative(ROOT, p).split('\\').join('/')] = readFileSync(p)
writeFileSync(join(DIST, `${manifest.id}-${manifest.version}.zip`), zipSync(files))
console.log('built', Object.keys(files).length, 'files')
